PARTS = {
    "[Content_Types].xml": CONTENT_TYPES,
    "_rels/.rels": PACKAGE_RELS,
    "ppt/presentation.xml": PRESENTATION,
    "ppt/_rels/presentation.xml.rels": PRESENTATION_RELS,
    "ppt/slideMasters/slideMaster1.xml": SLIDE_MASTER,
    "ppt/slideMasters/_rels/slideMaster1.xml.rels": SLIDE_MASTER_RELS,
    "ppt/slideLayouts/slideLayout1.xml": SLIDE_LAYOUT,
    "ppt/slideLayouts/_rels/slideLayout1.xml.rels": SLIDE_LAYOUT_RELS,
    "ppt/theme/theme1.xml": THEME,
    "ppt/slides/slide1.xml": SLIDE,
    "ppt/slides/_rels/slide1.xml.rels": SLIDE_RELS,
}


def create_pptx(output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(output, "w", compression=ZIP_DEFLATED) as package:
        for name, content in PARTS.items():
            package.writestr(name, content.encode("utf-8"))


def main() -> None:
    parser = argparse.ArgumentParser(description="生成隔离 PPTX 真实 OOXML 夹具")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("native-live-presentation.pptx"),
        help="输出真实 .pptx ZIP 路径",
    )
    args = parser.parse_args()
    create_pptx(args.output)
    print(args.output.resolve())


if __name__ == "__main__":
    main()
